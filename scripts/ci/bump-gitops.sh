#!/usr/bin/env bash
# Writes promoted digests into gitops/envs/<TARGET>/apps/<svc>.yaml.
#   dev:            commit + push to main (GitOps App is a ruleset bypass actor)
#   staging / prod: push a branch and open a PR for release-manager approval
# Env: TARGET, ITEMS (json), GH_TOKEN, RUN_URL
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# shellcheck source=../lib/common.sh
source "${ROOT}/scripts/lib/common.sh"
require_env TARGET ITEMS GH_TOKEN
require_cmd jq yq git gh

cd "${ROOT}"
git config user.name "shopsphere-gitops[bot]"
git config user.email "gitops-bot@users.noreply.github.com"

summary=""
while read -r item; do
  svc="$(jq -r .service <<<"${item}")"
  digest="$(jq -r .digest <<<"${item}")"
  tag="$(jq -r .tag <<<"${item}")"
  file="gitops/envs/${TARGET}/apps/${svc}.yaml"
  [[ -f "${file}" ]] || die "unknown service ${svc}"
  TAG="${tag}" DIGEST="${digest}" yq -i '.image.tag = strenv(TAG) | .image.digest = strenv(DIGEST)' "${file}"
  summary+="- \`${svc}\` -> \`${tag}\` (\`${digest:0:19}…\`)"$'\n'
done < <(jq -c '.[]' <<<"${ITEMS}")

if git diff --quiet; then
  log_info "nothing changed"
  exit 0
fi

title="deploy(${TARGET}): $(jq -r '[.[].service] | join(", ")' <<<"${ITEMS}")"
body="Promotion generated by ${RUN_URL:-ci}"$'\n\n'"${summary}"

if [[ "${TARGET}" == "dev" ]]; then
  git commit -am "${title}" -m "${body}"
  retry 3 2 git push origin HEAD:main
  log_info "pushed directly to main for dev"
else
  branch="promote/${TARGET}/$(date -u +%Y%m%d%H%M%S)"
  git switch -c "${branch}"
  git commit -am "${title}" -m "${body}"
  git push origin "${branch}"
  gh pr create --base main --head "${branch}" --title "${title}" --body "${body}" \
    --label "deploy:${TARGET}"
  gh pr merge "${branch}" --auto --squash   # merges once approvals + checks pass
  log_info "opened promotion PR ${branch}"
fi
