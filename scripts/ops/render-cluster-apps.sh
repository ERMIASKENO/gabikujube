#!/usr/bin/env bash
# Renders gitops/clusters/<env>/ (Argo CD Applications/ApplicationSets) from
# gitops/platform/components.yaml so component versions live in ONE place.
# CI (k8s-validate.yml) re-runs this and fails if the committed output differs.
#
# Usage: scripts/ops/render-cluster-apps.sh [dev staging prod]
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# shellcheck source=../lib/common.sh
source "${ROOT}/scripts/lib/common.sh"

REPO_URL="${REPO_URL:-https://github.com/ERMIASKENO/gabikujube.git}"
COMPONENTS="${ROOT}/gitops/platform/components.yaml"
GATEWAY_API_VERSION="${GATEWAY_API_VERSION:-v1.6.3}"

require_cmd yq

render_env() {
  local env="$1" out="${ROOT}/gitops/clusters/$1"
  mkdir -p "${out}"
  log_info "rendering ${out}"

  # --- platform add-ons (list generator built from components.yaml)
  local selector='.components'
  [[ "${env}" == "dev" ]] && selector='.components + .dev_only'
  local elements
  # one flow-mapping per component, indented under `elements:`
  elements="$(yq -o=yaml -I=0 "${selector} | .[] | [.] | . style=\"flow\"" "${COMPONENTS}" |
    sed -e 's/^\[\(.*\)\]$/          - \1/' -e 's/,\([^ ]\)/, \1/g')"

  cat >"${out}/platform.yaml" <<EOF
# GENERATED by scripts/ops/render-cluster-apps.sh - do not edit by hand
apiVersion: argoproj.io/v1alpha1
kind: ApplicationSet
metadata:
  name: platform
  namespace: argocd
  annotations:
    argocd.argoproj.io/sync-wave: "-10"
spec:
  goTemplate: true
  goTemplateOptions: ["missingkey=error"]
  generators:
    - list:
        elements:
${elements}
  template:
    metadata:
      name: '{{.name}}'
      labels:
        env: ${env}
        layer: platform
      annotations:
        argocd.argoproj.io/sync-wave: '{{.wave}}'
        notifications.argoproj.io/subscribe.on-health-degraded.teams: platform
    spec:
      project: platform
      sources:
        - repoURL: '{{.repo}}'
          chart: '{{.chart}}'
          targetRevision: '{{.version}}'
          helm:
            releaseName: '{{.name}}'
            ignoreMissingValueFiles: true
            valueFiles:
              - \$values/gitops/platform/values/{{.name}}.yaml
              - \$values/gitops/envs/${env}/platform/{{.name}}.yaml
        - repoURL: ${REPO_URL}
          targetRevision: main
          ref: values
      destination:
        server: https://kubernetes.default.svc
        namespace: '{{.namespace}}'
      syncPolicy:
        automated: { prune: true, selfHeal: true }
        syncOptions: [CreateNamespace=true, ServerSideApply=true, SkipDryRunOnMissingResource=true]
        retry:
          limit: 10
          backoff: { duration: 15s, factor: 2, maxDuration: 5m }
EOF

  # --- Gateway API CRDs (standard channel), straight from upstream at a pinned tag
  cat >"${out}/gateway-api-crds.yaml" <<EOF
# GENERATED by scripts/ops/render-cluster-apps.sh - do not edit by hand
apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: gateway-api-crds
  namespace: argocd
  annotations:
    argocd.argoproj.io/sync-wave: "-20"
spec:
  project: platform
  source:
    repoURL: https://github.com/kubernetes-sigs/gateway-api
    targetRevision: ${GATEWAY_API_VERSION}
    path: config/crd
  destination:
    server: https://kubernetes.default.svc
  syncPolicy:
    automated: { prune: false, selfHeal: true }   # never auto-delete CRDs (would delete every route)
    syncOptions: [ServerSideApply=true]           # CRDs exceed the client-side annotation size limit
EOF

  # --- cluster-wide config (Kustomize overlay)
  cat >"${out}/cluster-config.yaml" <<EOF
# GENERATED by scripts/ops/render-cluster-apps.sh - do not edit by hand
apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: cluster-config
  namespace: argocd
  annotations:
    argocd.argoproj.io/sync-wave: "0"
  finalizers: [resources-finalizer.argocd.argoproj.io]
spec:
  project: platform
  source:
    repoURL: ${REPO_URL}
    targetRevision: main
    path: gitops/cluster-config/overlays/${env}
  destination:
    server: https://kubernetes.default.svc
  syncPolicy:
    automated: { prune: true, selfHeal: true }
    syncOptions: [ServerSideApply=true, SkipDryRunOnMissingResource=true]
    retry:
      limit: 10
      backoff: { duration: 15s, factor: 2, maxDuration: 5m }
EOF

  # --- the 10 microservices: one Application per gitops/apps/<svc> directory
  cat >"${out}/apps.yaml" <<EOF
# GENERATED by scripts/ops/render-cluster-apps.sh - do not edit by hand
apiVersion: argoproj.io/v1alpha1
kind: ApplicationSet
metadata:
  name: shop-apps
  namespace: argocd
  annotations:
    argocd.argoproj.io/sync-wave: "10"
spec:
  goTemplate: true
  goTemplateOptions: ["missingkey=error"]
  generators:
    - git:
        repoURL: ${REPO_URL}
        revision: main
        directories:
          - path: gitops/apps/*
  template:
    metadata:
      name: '{{.path.basename}}'
      labels:
        env: ${env}
        layer: apps
      annotations:
        notifications.argoproj.io/subscribe.on-deployed.github-dispatch: ""
        notifications.argoproj.io/subscribe.on-health-degraded.teams: platform
      finalizers: [resources-finalizer.argocd.argoproj.io]
    spec:
      project: shop
      sources:
        - repoURL: ${REPO_URL}
          targetRevision: main
          path: deploy/charts/microservice
          helm:
            releaseName: '{{.path.basename}}'
            valueFiles:
              - \$values/gitops/apps/{{.path.basename}}/values.yaml
              - \$values/gitops/envs/${env}/values.yaml
              - \$values/gitops/envs/${env}/apps/{{.path.basename}}.yaml
        - repoURL: ${REPO_URL}
          targetRevision: main
          ref: values
      destination:
        server: https://kubernetes.default.svc
        namespace: shop
      syncPolicy:
        automated: { prune: true, selfHeal: true }
        syncOptions: [ServerSideApply=true, PruneLast=true, RespectIgnoreDifferences=true]
        retry:
          limit: 5
          backoff: { duration: 10s, factor: 2, maxDuration: 3m }
      # Argo Rollouts owns these fields at runtime; without this Argo CD would
      # "self-heal" a canary back to 0% in the middle of a rollout.
      ignoreDifferences:
        - group: gateway.networking.k8s.io
          kind: HTTPRoute
          jqPathExpressions: ['.spec.rules[].backendRefs[].weight']
        - group: ""
          kind: Service
          jqPathExpressions: ['.spec.selector["rollouts-pod-template-hash"]']
EOF

  cat >"${out}/kustomization.yaml" <<EOF
# GENERATED by scripts/ops/render-cluster-apps.sh - do not edit by hand
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ../../projects
  - gateway-api-crds.yaml
  - platform.yaml
  - cluster-config.yaml
  - apps.yaml
EOF

  # --- root app-of-apps (applied once by bootstrap, then self-managed)
  cat >"${ROOT}/gitops/bootstrap/root-${env}.yaml" <<EOF
# GENERATED by scripts/ops/render-cluster-apps.sh - kubectl apply -f once per cluster
apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: root
  namespace: argocd
  finalizers: [resources-finalizer.argocd.argoproj.io]
spec:
  project: default
  source:
    repoURL: ${REPO_URL}
    targetRevision: main
    path: gitops/clusters/${env}
  destination:
    server: https://kubernetes.default.svc
    namespace: argocd
  syncPolicy:
    automated: { prune: true, selfHeal: true }
EOF
}

envs=("$@")
[[ ${#envs[@]} -eq 0 ]] && envs=(dev staging prod)
for e in "${envs[@]}"; do
  render_env "${e}"
done
log_info "done"
